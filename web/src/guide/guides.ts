/** ตัดเหลือ segment แรกของ path เหมือน `activeNavPath` ใน App.tsx — `/installments/12` ใช้คู่มือของ `/installments` */
export function guideForPath(pathname: string): Guide | undefined {
  return GUIDES['/' + (pathname.split('/')[1] ?? '')];
}

/** กลุ่มในหน้า /help เรียงตามลำดับที่ผู้ใช้ใหม่ควรอ่าน ไม่ใช่ตามตัวอักษร — ทุก path ใน GUIDES อยู่ในกลุ่มเดียวเท่านั้น (เทสต์ตรวจ) */
export const HELP_GROUPS: readonly { id: 'start' | 'daily' | 'admin'; title: string; paths: readonly string[]; adminOnly?: boolean }[] = [
  { id: 'start', title: 'เริ่มต้น', paths: ['/accounts', '/dashboard'] },
  { id: 'daily', title: 'ใช้ประจำ', paths: ['/transactions', '/planning', '/installments', '/student-loan', '/tax-documents', '/tax', '/audit'] },
  { id: 'admin', title: 'ผู้ดูแล', paths: ['/settings'], adminOnly: true },
];

export type HelpSection = { path: string; guide: Guide; steps: GuideStep[] };
export type HelpGroup = { id: (typeof HELP_GROUPS)[number]['id']; title: string; sections: HelpSection[] };

// ไม่สนตัวพิมพ์ และค้นข้ามเครื่องหมาย ** ได้ ("กับเดือนอนาคต" เจอ "กับ**เดือนอนาคต**")
const fold = (text: string) => text.replaceAll('**', '').toLocaleLowerCase('th');

/**
 * เนื้อหาหน้า /help ของผู้ใช้คนนี้: หน้าที่ปิดอยู่ (features.ts) กลุ่ม/ขั้นของแอดมินสำหรับคนอื่น และกลุ่มที่ว่าง หายไป
 * `query` = คำค้น: ชื่อหรือคำอธิบายของหน้าตรง → ทุกขั้นของหน้านั้น ไม่งั้นเหลือเฉพาะขั้นที่ชื่อหรือเนื้อหาตรง
 */
export function helpSections(isAdmin: boolean, query = ''): HelpGroup[] {
  const q = fold(query.trim());
  const has = (text: string) => fold(text).includes(q);
  return HELP_GROUPS.filter((group) => isAdmin || !group.adminOnly)
    .map((group) => ({
      id: group.id,
      title: group.title,
      sections: group.paths.filter(isPageEnabled).flatMap((path): HelpSection[] => {
        const guide = GUIDES[path];
        if (!guide) return [];
        const visible = guide.steps.filter((step) => isAdmin || !step.adminOnly);
        const steps = q === '' || has(guide.title) || has(guide.purpose)
          ? visible
          : visible.filter((step) => has(step.title) || has(step.body));
        return steps.length > 0 ? [{ path, guide, steps }] : [];
      }),
    }))
    .filter((group) => group.sections.length > 0);
}
